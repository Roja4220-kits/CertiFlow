"""Suggest which file column probably belongs to a template field.

Pure Python, no field name is hard-coded. A suggestion is only a hint: the user
must confirm it, and it never changes what is generated by itself.
"""
from collections import Counter
from difflib import SequenceMatcher

SUGGEST_THRESHOLD = 0.5   # minimum similarity to be offered at all
AMBIGUITY_GAP = 0.08      # two candidates closer than this = "which one?"
MAX_CANDIDATES = 3


def _tokens(name):
    return {part for part in name.split("_") if part}


def _is_subsequence(short, long):
    letters = iter(long)
    return all(ch in letters for ch in short)


def _abbreviation_score(field, column):
    """'dept' for 'department', 'cert' for 'certificate': one is a short form of the other."""
    a, b = field.replace("_", ""), column.replace("_", "")
    short, long = (a, b) if len(a) <= len(b) else (b, a)
    if len(short) < 3 or short[0] != long[0]:
        return 0.0
    if long.startswith(short):
        return 0.7
    return 0.62 if _is_subsequence(short, long) else 0.0


def similarity(field, column):
    """0..1 similarity of two normalised names (spelling + shared words)."""
    ratio = SequenceMatcher(None, field, column).ratio()
    field_tokens, column_tokens = _tokens(field), _tokens(column)
    if not (field_tokens & column_tokens) and ratio < 0.75:
        abbreviation = _abbreviation_score(field, column)
        return abbreviation  # 0.0 when the words are unrelated: do not guess
    containment = len(field_tokens & column_tokens) / len(field_tokens) if field_tokens else 0.0
    return round(max(ratio, 0.5 * ratio + 0.5 * containment), 3)


def suggest_mappings(unmatched_fields, free_columns):
    """{field: {'status': 'suggested'|'ambiguous', 'candidates': [{'column','score'}]}}

    * unmatched_fields : template fields that have no column yet
    * free_columns     : file columns not already used by another field
    A field is 'ambiguous' when two columns are almost equally likely, or when
    the same column is the best guess for several fields.
    """
    ranked = {}
    for field in unmatched_fields:
        scored = [{"column": c, "score": similarity(field, c)} for c in free_columns]
        candidates = sorted((s for s in scored if s["score"] >= SUGGEST_THRESHOLD),
                            key=lambda s: (-s["score"], s["column"]))[:MAX_CANDIDATES]
        if candidates:
            ranked[field] = candidates

    claims = Counter(candidates[0]["column"] for candidates in ranked.values())
    result = {}
    for field, candidates in ranked.items():
        close_second = len(candidates) > 1 and candidates[0]["score"] - candidates[1]["score"] < AMBIGUITY_GAP
        shared = claims[candidates[0]["column"]] > 1
        result[field] = {"status": "ambiguous" if close_second or shared else "suggested",
                         "candidates": candidates}
    return result